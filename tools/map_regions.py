"""3D 지도 범위(남, 서, 북, 동). 받기·가공 스크립트와 화면이 모두 이 값을 쓴다.

범위는 R-ONE 상권 경계에 여백을 둔 사각형이다. 경계를 아직 못 딴 곳은 OSM 장소로 임시로 잡고 '임시'라고 적는다.
"""
REGIONS = {
    # R-ONE 남포동 상권 경계(129.0214~129.0362, 35.0960~35.1049)에 여백. 대상지에서 빠짐(2026-11-27).
    'nampo': (35.0945, 129.0200, 35.1060, 129.0380),
    # 거제 옥포: 임시 범위(옥포 상가 밀집지 + 여백). R-ONE 경계를 따면 바꾼다.
    'okpo': (34.8835, 128.6835, 34.9005, 128.7040),
}


def bbox(name):
    b = REGIONS.get(name)
    if not b:
        raise SystemExit(f'지역 {name!r} 의 범위가 아직 없습니다. tools/map_regions.py 에 넣어 주세요.')
    return b
